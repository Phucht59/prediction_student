CREATE SCHEMA IF NOT EXISTS raw;

CREATE TABLE IF NOT EXISTS raw.uci_mat (
    row_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payload JSONB NOT NULL,
    source_file TEXT NOT NULL DEFAULT 'student-mat.csv',
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS raw.uci_por (
    row_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payload JSONB NOT NULL,
    source_file TEXT NOT NULL DEFAULT 'student-por.csv',
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS raw.oulad_courses (
    code_module TEXT NOT NULL,
    code_presentation TEXT NOT NULL,
    module_presentation_length INTEGER,
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (code_module, code_presentation)
);

CREATE TABLE IF NOT EXISTS raw.oulad_assessments (
    id_assessment INTEGER PRIMARY KEY,
    code_module TEXT NOT NULL,
    code_presentation TEXT NOT NULL,
    assessment_type TEXT,
    date DOUBLE PRECISION,
    weight DOUBLE PRECISION,
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    FOREIGN KEY (code_module, code_presentation)
        REFERENCES raw.oulad_courses (code_module, code_presentation)
);

CREATE TABLE IF NOT EXISTS raw.oulad_vle (
    id_site INTEGER PRIMARY KEY,
    code_module TEXT NOT NULL,
    code_presentation TEXT NOT NULL,
    activity_type TEXT,
    week_from DOUBLE PRECISION,
    week_to DOUBLE PRECISION,
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    FOREIGN KEY (code_module, code_presentation)
        REFERENCES raw.oulad_courses (code_module, code_presentation)
);

CREATE TABLE IF NOT EXISTS raw.oulad_student_info (
    id_student BIGINT NOT NULL,
    code_module TEXT NOT NULL,
    code_presentation TEXT NOT NULL,
    gender TEXT,
    region TEXT,
    highest_education TEXT,
    imd_band TEXT,
    age_band TEXT,
    num_of_prev_attempts INTEGER,
    studied_credits INTEGER,
    disability TEXT,
    final_result TEXT,
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (id_student, code_module, code_presentation),
    FOREIGN KEY (code_module, code_presentation)
        REFERENCES raw.oulad_courses (code_module, code_presentation)
);

CREATE TABLE IF NOT EXISTS raw.oulad_student_registration (
    id_student BIGINT NOT NULL,
    code_module TEXT NOT NULL,
    code_presentation TEXT NOT NULL,
    date_registration DOUBLE PRECISION,
    date_unregistration DOUBLE PRECISION,
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (id_student, code_module, code_presentation),
    FOREIGN KEY (id_student, code_module, code_presentation)
        REFERENCES raw.oulad_student_info (id_student, code_module, code_presentation)
);

CREATE TABLE IF NOT EXISTS raw.oulad_student_assessment (
    id_assessment INTEGER NOT NULL,
    id_student BIGINT NOT NULL,
    date_submitted DOUBLE PRECISION,
    is_banked INTEGER,
    score DOUBLE PRECISION,
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (id_assessment, id_student),
    FOREIGN KEY (id_assessment) REFERENCES raw.oulad_assessments (id_assessment)
);

CREATE TABLE IF NOT EXISTS raw.oulad_student_vle (
    row_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code_module TEXT NOT NULL,
    code_presentation TEXT NOT NULL,
    id_student BIGINT NOT NULL,
    id_site INTEGER NOT NULL,
    date DOUBLE PRECISION,
    sum_click INTEGER,
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    FOREIGN KEY (id_site) REFERENCES raw.oulad_vle (id_site),
    FOREIGN KEY (id_student, code_module, code_presentation)
        REFERENCES raw.oulad_student_info (id_student, code_module, code_presentation)
);

CREATE TABLE IF NOT EXISTS raw.load_manifest (
    table_name TEXT PRIMARY KEY,
    source_path TEXT NOT NULL,
    source_sha256 CHAR(64) NOT NULL,
    row_count BIGINT NOT NULL,
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS oulad_assessments_course_idx
    ON raw.oulad_assessments (code_module, code_presentation);
CREATE INDEX IF NOT EXISTS oulad_vle_course_idx
    ON raw.oulad_vle (code_module, code_presentation);
CREATE INDEX IF NOT EXISTS oulad_student_vle_id_site_idx
    ON raw.oulad_student_vle (id_site);
CREATE INDEX IF NOT EXISTS oulad_student_vle_student_idx
    ON raw.oulad_student_vle (id_student, code_module, code_presentation);

COMMENT ON SCHEMA raw IS 'Landing zone for source CSVs. UCI is JSONB dumps; OULAD is typed and related.';
COMMENT ON TABLE raw.uci_mat IS 'UCI student-mat.csv rows (JSONB landing, no natural FK).';
COMMENT ON TABLE raw.uci_por IS 'UCI student-por.csv rows (JSONB landing, no natural FK).';
COMMENT ON TABLE raw.load_manifest IS 'Loader checksum log; not part of the domain model.';
