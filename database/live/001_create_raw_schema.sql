CREATE TABLE IF NOT EXISTS raw.oulad (
    row_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_key TEXT NOT NULL DEFAULT 'oulad'
        REFERENCES raw.dataset (dataset_key),
    source_file TEXT NOT NULL,
    payload JSONB NOT NULL,
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT oulad_dataset_chk CHECK (dataset_key = 'oulad')
);

CREATE INDEX IF NOT EXISTS oulad_source_file_idx ON raw.oulad (source_file);

