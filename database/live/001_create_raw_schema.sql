CREATE SCHEMA IF NOT EXISTS raw;

CREATE TABLE IF NOT EXISTS raw.dataset (
    dataset_key TEXT PRIMARY KEY,
    display_name TEXT NOT NULL,
    files JSONB NOT NULL DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

INSERT INTO raw.dataset (dataset_key, display_name) VALUES
    ('student_mat', 'UCI Student Performance (Math)'),
    ('student_por', 'UCI Student Performance (Portuguese)'),
    ('oulad', 'Open University Learning Analytics Dataset')
ON CONFLICT (dataset_key) DO NOTHING;

-- One table per source dataset. UCI is typed; OULAD keeps all 7 CSVs as JSONB rows.
CREATE TABLE IF NOT EXISTS raw.student_mat (
    row_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_key TEXT NOT NULL DEFAULT 'student_mat'
        REFERENCES raw.dataset (dataset_key),
    school TEXT,
    sex TEXT,
    age INTEGER,
    address TEXT,
    famsize TEXT,
    pstatus TEXT,
    medu INTEGER,
    fedu INTEGER,
    mjob TEXT,
    fjob TEXT,
    reason TEXT,
    guardian TEXT,
    traveltime INTEGER,
    studytime INTEGER,
    failures INTEGER,
    schoolsup TEXT,
    famsup TEXT,
    paid TEXT,
    activities TEXT,
    nursery TEXT,
    higher TEXT,
    internet TEXT,
    romantic TEXT,
    famrel INTEGER,
    freetime INTEGER,
    goout INTEGER,
    dalc INTEGER,
    walc INTEGER,
    health INTEGER,
    absences INTEGER,
    g1 INTEGER,
    g2 INTEGER,
    g3 INTEGER,
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT student_mat_dataset_chk CHECK (dataset_key = 'student_mat')
);

