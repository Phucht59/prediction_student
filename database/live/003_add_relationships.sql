-- Make pgAdmin ERD show real relationships.
-- Serving layer: catalog -> prediction -> recommendation.
-- Raw OULAD: courses star. UCI JSONB dumps stay unlinked on purpose.

SET statement_timeout = 0;
SET maintenance_work_mem = '1GB';

-- Dead column from dropped data.feature_snapshot.
ALTER TABLE prediction.prediction DROP COLUMN IF EXISTS snapshot_id;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'prediction_enrollment_id_fkey') THEN
        ALTER TABLE prediction.prediction
            ADD CONSTRAINT prediction_enrollment_id_fkey
            FOREIGN KEY (enrollment_id) REFERENCES catalog.enrollment (enrollment_id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'recommendation_prediction_id_fkey') THEN
        ALTER TABLE recommendation.recommendation
            ADD CONSTRAINT recommendation_prediction_id_fkey
            FOREIGN KEY (prediction_id) REFERENCES prediction.prediction (prediction_id);
    END IF;
END $$;

ALTER TABLE raw.oulad_courses
    ALTER COLUMN code_module SET NOT NULL,
    ALTER COLUMN code_presentation SET NOT NULL;
ALTER TABLE raw.oulad_assessments
    ALTER COLUMN id_assessment SET NOT NULL,
    ALTER COLUMN code_module SET NOT NULL,
    ALTER COLUMN code_presentation SET NOT NULL;
ALTER TABLE raw.oulad_vle
    ALTER COLUMN id_site SET NOT NULL,
    ALTER COLUMN code_module SET NOT NULL,
    ALTER COLUMN code_presentation SET NOT NULL;
ALTER TABLE raw.oulad_student_info
    ALTER COLUMN id_student SET NOT NULL,
    ALTER COLUMN code_module SET NOT NULL,
    ALTER COLUMN code_presentation SET NOT NULL;
ALTER TABLE raw.oulad_student_registration
    ALTER COLUMN id_student SET NOT NULL,
    ALTER COLUMN code_module SET NOT NULL,
    ALTER COLUMN code_presentation SET NOT NULL;
ALTER TABLE raw.oulad_student_assessment
    ALTER COLUMN id_assessment SET NOT NULL,
    ALTER COLUMN id_student SET NOT NULL;
ALTER TABLE raw.oulad_student_vle
    ALTER COLUMN code_module SET NOT NULL,
    ALTER COLUMN code_presentation SET NOT NULL,
    ALTER COLUMN id_student SET NOT NULL,
    ALTER COLUMN id_site SET NOT NULL;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'oulad_courses_pkey') THEN
        ALTER TABLE raw.oulad_courses
            ADD CONSTRAINT oulad_courses_pkey PRIMARY KEY (code_module, code_presentation);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'oulad_assessments_pkey') THEN
        ALTER TABLE raw.oulad_assessments
            ADD CONSTRAINT oulad_assessments_pkey PRIMARY KEY (id_assessment);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'oulad_vle_pkey') THEN
        ALTER TABLE raw.oulad_vle
            ADD CONSTRAINT oulad_vle_pkey PRIMARY KEY (id_site);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'oulad_student_info_pkey') THEN
        ALTER TABLE raw.oulad_student_info
            ADD CONSTRAINT oulad_student_info_pkey PRIMARY KEY (id_student, code_module, code_presentation);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'oulad_student_registration_pkey') THEN
        ALTER TABLE raw.oulad_student_registration
            ADD CONSTRAINT oulad_student_registration_pkey PRIMARY KEY (id_student, code_module, code_presentation);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'oulad_student_assessment_pkey') THEN
        ALTER TABLE raw.oulad_student_assessment
            ADD CONSTRAINT oulad_student_assessment_pkey PRIMARY KEY (id_assessment, id_student);
    END IF;
END $$;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'raw' AND table_name = 'oulad_student_vle' AND column_name = 'row_id'
    ) THEN
        ALTER TABLE raw.oulad_student_vle
            ADD COLUMN row_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY;
    ELSIF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'oulad_student_vle_pkey') THEN
        ALTER TABLE raw.oulad_student_vle
            ADD CONSTRAINT oulad_student_vle_pkey PRIMARY KEY (row_id);
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS oulad_assessments_course_idx
    ON raw.oulad_assessments (code_module, code_presentation);
CREATE INDEX IF NOT EXISTS oulad_vle_course_idx
    ON raw.oulad_vle (code_module, code_presentation);
CREATE INDEX IF NOT EXISTS oulad_student_vle_id_site_idx
    ON raw.oulad_student_vle (id_site);
CREATE INDEX IF NOT EXISTS oulad_student_vle_student_idx
    ON raw.oulad_student_vle (id_student, code_module, code_presentation);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'oulad_assessments_course_fkey') THEN
        ALTER TABLE raw.oulad_assessments
            ADD CONSTRAINT oulad_assessments_course_fkey
            FOREIGN KEY (code_module, code_presentation)
            REFERENCES raw.oulad_courses (code_module, code_presentation);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'oulad_vle_course_fkey') THEN
        ALTER TABLE raw.oulad_vle
            ADD CONSTRAINT oulad_vle_course_fkey
            FOREIGN KEY (code_module, code_presentation)
            REFERENCES raw.oulad_courses (code_module, code_presentation);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'oulad_student_info_course_fkey') THEN
        ALTER TABLE raw.oulad_student_info
            ADD CONSTRAINT oulad_student_info_course_fkey
            FOREIGN KEY (code_module, code_presentation)
            REFERENCES raw.oulad_courses (code_module, code_presentation);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'oulad_student_registration_student_fkey') THEN
        ALTER TABLE raw.oulad_student_registration
            ADD CONSTRAINT oulad_student_registration_student_fkey
            FOREIGN KEY (id_student, code_module, code_presentation)
            REFERENCES raw.oulad_student_info (id_student, code_module, code_presentation);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'oulad_student_assessment_assessment_fkey') THEN
        ALTER TABLE raw.oulad_student_assessment
            ADD CONSTRAINT oulad_student_assessment_assessment_fkey
            FOREIGN KEY (id_assessment) REFERENCES raw.oulad_assessments (id_assessment);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'oulad_student_vle_id_site_fkey') THEN
        ALTER TABLE raw.oulad_student_vle
            ADD CONSTRAINT oulad_student_vle_id_site_fkey
            FOREIGN KEY (id_site) REFERENCES raw.oulad_vle (id_site);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'oulad_student_vle_student_fkey') THEN
        ALTER TABLE raw.oulad_student_vle
            ADD CONSTRAINT oulad_student_vle_student_fkey
            FOREIGN KEY (id_student, code_module, code_presentation)
            REFERENCES raw.oulad_student_info (id_student, code_module, code_presentation);
    END IF;
END $$;

DROP INDEX IF EXISTS catalog.idx_enrollment_course;
DROP INDEX IF EXISTS catalog.idx_enrollment_student;

COMMENT ON SCHEMA catalog IS 'Student and course identities used by prediction/recommendation.';
COMMENT ON SCHEMA prediction IS 'Hybrid C0 model runs and enrollment-stage risk scores.';
COMMENT ON SCHEMA recommendation IS 'V3 Five-EBM-C0 ranked actions.';
COMMENT ON SCHEMA raw IS 'Landing zone for source CSVs. UCI is JSONB dumps; OULAD is typed and related.';
COMMENT ON TABLE raw.uci_mat IS 'UCI student-mat.csv rows (JSONB landing, no natural FK).';
COMMENT ON TABLE raw.uci_por IS 'UCI student-por.csv rows (JSONB landing, no natural FK).';
COMMENT ON TABLE raw.load_manifest IS 'Loader checksum log; not part of the domain model.';
COMMENT ON TABLE prediction.prediction IS 'C0 OOF risk probability per enrollment and stage.';
COMMENT ON TABLE recommendation.recommendation IS 'One V3 recommendation set per C0 prediction.';
