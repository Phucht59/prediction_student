BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '5min';
SELECT pg_advisory_xact_lock(hashtext('final_database_v1'));

CREATE TABLE IF NOT EXISTS recommendation.policy (
    policy_id TEXT PRIMARY KEY,
    policy_name TEXT NOT NULL,
    version_label TEXT NOT NULL,
    rules JSONB NOT NULL CHECK (jsonb_typeof(rules) = 'object'),
    policy_sha256 CHAR(64) NOT NULL CHECK (policy_sha256 ~ '^[0-9a-f]{64}$'),
    status TEXT NOT NULL CHECK (status IN ('active', 'retired')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (policy_name, version_label)
);

CREATE TABLE IF NOT EXISTS recommendation.risk_profile (
    risk_profile_id TEXT PRIMARY KEY,
    run_id TEXT NOT NULL REFERENCES ml.run(run_id) ON DELETE RESTRICT,
    record_pk BIGINT NOT NULL REFERENCES catalog.record(record_pk) ON DELETE RESTRICT,
    risk_probability DOUBLE PRECISION NOT NULL CHECK (risk_probability >= 0 AND risk_probability <= 1),
    predicted_label TEXT NOT NULL CHECK (predicted_label IN ('At-risk', 'Not-at-risk')),
    risk_band TEXT NOT NULL,
    uncertainty DOUBLE PRECISION CHECK (uncertainty IS NULL OR (uncertainty >= 0 AND uncertainty <= 1)),
    uncertainty_status TEXT,
    escalation_required BOOLEAN NOT NULL DEFAULT FALSE,
    payload JSONB NOT NULL,
    lineage JSONB NOT NULL,
    checksum CHAR(64) NOT NULL CHECK (checksum ~ '^[0-9a-f]{64}$'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (run_id, record_pk)
);

CREATE TABLE IF NOT EXISTS recommendation.plan (
    plan_id TEXT PRIMARY KEY,
    risk_profile_id TEXT NOT NULL REFERENCES recommendation.risk_profile(risk_profile_id) ON DELETE RESTRICT,
    policy_id TEXT NOT NULL REFERENCES recommendation.policy(policy_id) ON DELETE RESTRICT,
    revision_no INTEGER NOT NULL CHECK (revision_no > 0),
    priority TEXT NOT NULL,
    goal TEXT NOT NULL,
    rationale TEXT NOT NULL,
    status TEXT NOT NULL,
    payload JSONB NOT NULL,
    checksum CHAR(64) NOT NULL CHECK (checksum ~ '^[0-9a-f]{64}$'),
    supersedes_plan_id TEXT REFERENCES recommendation.plan(plan_id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (risk_profile_id, revision_no)
);

CREATE TABLE IF NOT EXISTS recommendation.action (
    action_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id TEXT NOT NULL REFERENCES recommendation.plan(plan_id) ON DELETE RESTRICT,
    action_code TEXT NOT NULL,
    week_no INTEGER NOT NULL CHECK (week_no >= 0),
    priority INTEGER NOT NULL CHECK (priority > 0),
    workload_minutes INTEGER NOT NULL CHECK (workload_minutes >= 0),
    status TEXT NOT NULL,
    action_text TEXT NOT NULL,
    payload JSONB NOT NULL,
    checksum CHAR(64) NOT NULL CHECK (checksum ~ '^[0-9a-f]{64}$'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (plan_id, action_code, week_no, priority)
);

CREATE TABLE IF NOT EXISTS recommendation.review (
    review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id TEXT NOT NULL REFERENCES recommendation.plan(plan_id) ON DELETE RESTRICT,
    action_id BIGINT REFERENCES recommendation.action(action_id) ON DELETE RESTRICT,
    review_type TEXT NOT NULL CHECK (review_type IN ('advisor', 'expert', 'follow_up', 'system_validation')),
    reviewer_key TEXT NOT NULL,
    decision TEXT,
    score DOUBLE PRECISION,
    status TEXT NOT NULL,
    reason TEXT,
    payload JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
COMMIT;
