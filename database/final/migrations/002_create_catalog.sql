BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '5min';
SELECT pg_advisory_xact_lock(hashtext('final_database_v1'));

CREATE TABLE IF NOT EXISTS catalog.dataset (
    dataset_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug TEXT NOT NULL UNIQUE CHECK (slug IN ('student-mat', 'student-por', 'oulad')),
    display_name TEXT NOT NULL,
    task_type TEXT NOT NULL CHECK (task_type IN ('multiclass_student_performance', 'binary_student_risk')),
    class_labels JSONB NOT NULL CHECK (jsonb_typeof(class_labels) = 'array'),
    description TEXT,
    source_uri TEXT,
    license_note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS catalog.dataset_version (
    dataset_version_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id BIGINT NOT NULL REFERENCES catalog.dataset(dataset_id) ON DELETE RESTRICT,
    version_label TEXT NOT NULL,
    source_sha256 CHAR(64) NOT NULL CHECK (source_sha256 ~ '^[0-9a-f]{64}$'),
    row_count BIGINT NOT NULL CHECK (row_count >= 0),
    data_schema JSONB NOT NULL DEFAULT '{}'::jsonb,
    source_files JSONB NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(source_files) = 'array'),
    status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'sealed', 'retired')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    sealed_at TIMESTAMPTZ,
    UNIQUE (dataset_id, version_label),
    CHECK ((status = 'sealed' AND sealed_at IS NOT NULL) OR status <> 'sealed')
);

CREATE TABLE IF NOT EXISTS catalog.record (
    record_pk BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_version_id BIGINT NOT NULL REFERENCES catalog.dataset_version(dataset_version_id) ON DELETE RESTRICT,
    source_record_id TEXT NOT NULL,
    student_key TEXT,
    subject TEXT,
    code_module TEXT,
    code_presentation TEXT,
    target_label TEXT,
    target_numeric DOUBLE PRECISION,
    attributes JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (dataset_version_id, source_record_id)
);

CREATE OR REPLACE FUNCTION system.reject_sealed_dataset_mutation()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.status = 'sealed' THEN
        RAISE EXCEPTION 'sealed dataset version is immutable';
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS protect_sealed_dataset_version ON catalog.dataset_version;
CREATE TRIGGER protect_sealed_dataset_version
BEFORE UPDATE OR DELETE ON catalog.dataset_version
FOR EACH ROW EXECUTE FUNCTION system.reject_sealed_dataset_mutation();
COMMIT;
