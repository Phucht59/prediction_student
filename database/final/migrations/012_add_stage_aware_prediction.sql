BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '5min';
SELECT pg_advisory_xact_lock(hashtext('unified_stage_aware_v1'));

ALTER TABLE ml.metric
    ADD COLUMN IF NOT EXISTS prediction_stage TEXT;

DROP INDEX IF EXISTS ml.metric_natural_key_idx;
CREATE UNIQUE INDEX metric_natural_key_idx
    ON ml.metric(
        run_id, metric_name, scope, aggregation, prediction_stage,
        class_label, budget, fold, seed
    )
    NULLS NOT DISTINCT;

CREATE TABLE IF NOT EXISTS ml.prediction (
    prediction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id TEXT NOT NULL REFERENCES ml.run(run_id) ON DELETE RESTRICT,
    record_pk BIGINT NOT NULL REFERENCES catalog.record(record_pk) ON DELETE RESTRICT,
    prediction_stage TEXT NOT NULL,
    predicted_label TEXT NOT NULL,
    probabilities JSONB NOT NULL,
    outer_fold INTEGER,
    aggregation TEXT NOT NULL,
    source_artifact TEXT NOT NULL,
    source_sha256 CHAR(64) NOT NULL CHECK (source_sha256 ~ '^[0-9a-f]{64}$'),
    detail JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (run_id, record_pk, prediction_stage)
);

CREATE INDEX IF NOT EXISTS prediction_record_stage_idx
    ON ml.prediction(record_pk, prediction_stage);
CREATE INDEX IF NOT EXISTS prediction_run_stage_idx
    ON ml.prediction(run_id, prediction_stage);

ALTER TABLE recommendation.risk_profile
    ADD COLUMN IF NOT EXISTS prediction_stage TEXT NOT NULL DEFAULT 'F2_MIDDLE';

CREATE OR REPLACE VIEW ml.stage_model_results AS
SELECT d.slug AS dataset,
       m.model_key,
       m.official_name,
       m.is_selected,
       mt.prediction_stage,
       MAX(mt.metric_value) FILTER (WHERE mt.metric_name = 'accuracy') AS accuracy,
       MAX(mt.metric_value) FILTER (WHERE mt.metric_name = 'balanced_accuracy') AS balanced_accuracy,
       MAX(mt.metric_value) FILTER (WHERE mt.metric_name = 'macro_f1') AS macro_f1,
       MAX(mt.metric_value) FILTER (WHERE mt.metric_name = 'pr_auc') AS pr_auc,
       MAX(mt.metric_value) FILTER (WHERE mt.metric_name = 'roc_auc') AS roc_auc,
       MAX(mt.metric_value) FILTER (WHERE mt.metric_name = 'brier') AS brier,
       MAX(mt.metric_value) FILTER (WHERE mt.metric_name = 'nll') AS nll,
       MAX(mt.metric_value) FILTER (WHERE mt.metric_name = 'ece') AS ece
FROM ml.model m
JOIN catalog.dataset d ON d.dataset_id = m.dataset_id
JOIN ml.run r ON r.model_id = m.model_id AND r.status = 'completed'
JOIN ml.metric mt ON mt.run_id = r.run_id AND mt.scope = 'stage'
GROUP BY d.slug, m.model_key, m.official_name, m.is_selected, mt.prediction_stage;

DROP VIEW IF EXISTS recommendation.plan_summary;
CREATE VIEW recommendation.plan_summary AS
SELECT cr.source_record_id,
       rp.prediction_stage,
       rp.risk_probability,
       rp.risk_band,
       rp.uncertainty,
       rp.escalation_required,
       p.plan_id,
       p.status AS plan_status,
       COUNT(DISTINCT a.action_id) AS action_count,
       COALESCE(SUM(a.workload_minutes), 0) AS workload_minutes,
       COALESCE(MAX(rv.status), 'PENDING_EXPERT_LABELS') AS review_status
FROM recommendation.plan p
JOIN recommendation.risk_profile rp ON rp.risk_profile_id = p.risk_profile_id
JOIN catalog.record cr ON cr.record_pk = rp.record_pk
LEFT JOIN recommendation.action a ON a.plan_id = p.plan_id
LEFT JOIN recommendation.review rv ON rv.plan_id = p.plan_id
GROUP BY cr.source_record_id, rp.prediction_stage, rp.risk_probability,
         rp.risk_band, rp.uncertainty, rp.escalation_required, p.plan_id, p.status;
COMMIT;
