BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '5min';
SELECT pg_advisory_xact_lock(hashtext('final_database_v1'));

CREATE TABLE IF NOT EXISTS ml.model (
    model_id TEXT PRIMARY KEY,
    dataset_id BIGINT NOT NULL REFERENCES catalog.dataset(dataset_id) ON DELETE RESTRICT,
    model_key TEXT NOT NULL,
    official_name TEXT NOT NULL,
    model_family TEXT NOT NULL,
    is_selected BOOLEAN NOT NULL DEFAULT FALSE,
    config JSONB NOT NULL DEFAULT '{}'::jsonb,
    config_sha256 CHAR(64) NOT NULL CHECK (config_sha256 ~ '^[0-9a-f]{64}$'),
    protocol_version TEXT NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('selected', 'comparator', 'retired')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (dataset_id, model_key)
);

CREATE TABLE IF NOT EXISTS ml.run (
    run_id TEXT PRIMARY KEY,
    model_id TEXT NOT NULL REFERENCES ml.model(model_id) ON DELETE RESTRICT,
    dataset_version_id BIGINT NOT NULL REFERENCES catalog.dataset_version(dataset_version_id) ON DELETE RESTRICT,
    run_type TEXT NOT NULL CHECK (run_type IN ('official_final', 'comparator_completion', 'evaluation_only')),
    result_scope TEXT NOT NULL,
    aggregation TEXT NOT NULL,
    protocol_version TEXT NOT NULL,
    protocol_sha256 CHAR(64) CHECK (protocol_sha256 IS NULL OR protocol_sha256 ~ '^[0-9a-f]{64}$'),
    split_manifest_sha256 CHAR(64) CHECK (split_manifest_sha256 IS NULL OR split_manifest_sha256 ~ '^[0-9a-f]{64}$'),
    feature_contract_sha256 CHAR(64) CHECK (feature_contract_sha256 IS NULL OR feature_contract_sha256 ~ '^[0-9a-f]{64}$'),
    git_commit TEXT,
    seed_summary JSONB NOT NULL DEFAULT '{}'::jsonb,
    hardware JSONB NOT NULL DEFAULT '{}'::jsonb,
    status TEXT NOT NULL CHECK (status IN ('pending', 'running', 'completed', 'failed')),
    started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (model_id, dataset_version_id, result_scope)
);

CREATE TABLE IF NOT EXISTS ml.artifact (
    artifact_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id TEXT REFERENCES ml.run(run_id) ON DELETE RESTRICT,
    dataset_version_id BIGINT REFERENCES catalog.dataset_version(dataset_version_id) ON DELETE RESTRICT,
    artifact_kind TEXT NOT NULL,
    storage_path TEXT NOT NULL,
    sha256 CHAR(64) NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    byte_count BIGINT CHECK (byte_count IS NULL OR byte_count >= 0),
    row_count BIGINT CHECK (row_count IS NULL OR row_count >= 0),
    media_type TEXT,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (run_id, artifact_kind, storage_path)
);

CREATE TABLE IF NOT EXISTS ml.metric (
    metric_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id TEXT NOT NULL REFERENCES ml.run(run_id) ON DELETE RESTRICT,
    metric_name TEXT NOT NULL,
    metric_value DOUBLE PRECISION,
    scope TEXT NOT NULL,
    aggregation TEXT NOT NULL,
    class_label TEXT,
    budget DOUBLE PRECISION CHECK (budget IS NULL OR (budget >= 0 AND budget <= 1)),
    fold INTEGER,
    seed INTEGER,
    unit TEXT,
    detail JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE OR REPLACE FUNCTION system.reject_completed_final_run_mutation()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF OLD.status = 'completed' AND OLD.run_type IN ('official_final', 'comparator_completion') THEN
        RAISE EXCEPTION 'completed final run is immutable';
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS protect_completed_final_run ON ml.run;
CREATE TRIGGER protect_completed_final_run
BEFORE UPDATE OR DELETE ON ml.run
FOR EACH ROW EXECUTE FUNCTION system.reject_completed_final_run_mutation();
COMMIT;
