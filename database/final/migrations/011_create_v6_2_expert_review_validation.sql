BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '5min';
SELECT pg_advisory_xact_lock(hashtext('final_database_v6_2_expert_review'));

-- Additive V6.2 structures. They do not modify model runs, predictions,
-- recommendation plans, or frozen V6 evidence.
CREATE TABLE IF NOT EXISTS recommendation.expert_review_case (
    case_id TEXT PRIMARY KEY,
    schema_version TEXT NOT NULL,
    case_checksum CHAR(64) NOT NULL CHECK (case_checksum ~ '^[0-9a-f]{64}$'),
    stratum JSONB NOT NULL CHECK (jsonb_typeof(stratum) = 'object'),
    payload JSONB NOT NULL CHECK (jsonb_typeof(payload) = 'object'),
    status TEXT NOT NULL CHECK (status IN ('prepared', 'retired')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS recommendation.expert_plan_review (
    expert_plan_review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id TEXT NOT NULL
        REFERENCES recommendation.expert_review_case(case_id) ON DELETE RESTRICT,
    schema_version TEXT NOT NULL,
    reviewer_key TEXT NOT NULL CHECK (reviewer_key ~ '^E[0-9]{2,}$'),
    plan_score SMALLINT NOT NULL CHECK (plan_score BETWEEN 1 AND 5),
    missing_action BOOLEAN NOT NULL,
    missing_action_text TEXT,
    escalation_judgement TEXT NOT NULL CHECK (
        escalation_judgement IN
        ('CORRECT', 'OVER_ESCALATED', 'UNDER_ESCALATED', 'UNSURE')
    ),
    reason_support TEXT NOT NULL CHECK (
        reason_support IN ('SUPPORTED', 'PARTIAL', 'UNSUPPORTED', 'UNSURE')
    ),
    safety_workload TEXT NOT NULL CHECK (
        safety_workload IN ('SAFE', 'CONCERN', 'UNSAFE', 'UNSURE')
    ),
    safety_note TEXT,
    payload JSONB NOT NULL DEFAULT '{}'::jsonb,
    checksum CHAR(64) NOT NULL CHECK (checksum ~ '^[0-9a-f]{64}$'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (case_id, reviewer_key),
    CHECK (NOT missing_action OR NULLIF(BTRIM(missing_action_text), '') IS NOT NULL),
    CHECK (
        safety_workload NOT IN ('CONCERN', 'UNSAFE')
        OR NULLIF(BTRIM(safety_note), '') IS NOT NULL
    )
);

CREATE TABLE IF NOT EXISTS recommendation.expert_action_review (
    expert_action_review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id TEXT NOT NULL
        REFERENCES recommendation.expert_review_case(case_id) ON DELETE RESTRICT,
    schema_version TEXT NOT NULL,
    reviewer_key TEXT NOT NULL CHECK (reviewer_key ~ '^E[0-9]{2,}$'),
    action_code TEXT NOT NULL,
    relevance TEXT NOT NULL CHECK (
        relevance IN ('APPROVE', 'PARTIAL', 'UNSURE', 'REJECT')
    ),
    comment TEXT,
    payload JSONB NOT NULL DEFAULT '{}'::jsonb,
    checksum CHAR(64) NOT NULL CHECK (checksum ~ '^[0-9a-f]{64}$'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (case_id, reviewer_key, action_code)
);

CREATE INDEX IF NOT EXISTS idx_expert_plan_review_case
    ON recommendation.expert_plan_review(case_id);
CREATE INDEX IF NOT EXISTS idx_expert_action_review_case
    ON recommendation.expert_action_review(case_id);

COMMIT;
